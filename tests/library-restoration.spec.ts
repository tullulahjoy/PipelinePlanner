async function setup(page: Page) {
  await page.goto('/workspaces')
  await page.getByLabel('Workspace name').fill('Restoration team')
  await page.getByRole('button', { name: 'Create workspace', exact: true }).click()
  await page.getByRole('dialog', { name: 'Your pipeline plan starts here', exact: true }).getByRole('button', { name: 'Got it', exact: true }).click()
  return page.url().split('/')[4]
}
async function library(page: Page, section: 'phases' | 'templates') {
  const exit = page.getByRole('button', { name: 'Exit edit mode', exact: true })
  if (await exit.isVisible()) await exit.click()
  await page.getByRole('navigation').getByRole('link', { name: 'Library', exact: true }).click()
  await page.getByRole('button', { name: section === 'phases' ? /^Manage phases/ : /^Manage templates/ }).click()
}
async function createPhase(page: Page, name = 'Evaluation', weeks = 2) {
  await library(page, 'phases')
  await page.getByRole('button', { name: '+ Create phase', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Create phase', exact: true })
  await dialog.getByLabel('Phase name', { exact: true }).fill(name)
  await dialog.getByLabel('Default duration (weeks)').fill(String(weeks))
  await dialog.getByRole('button', { name: 'Create phase', exact: true }).click()
  await expect(dialog).toHaveCount(0)
}
async function records(page: Page, id: string): Promise<{ library: Library; templates: ProcurementTemplate[]; pipelines: SavedPipeline[] }> {
  return page.evaluate(async id => {
    const path = '/src/data/local-data.ts'; const { localData } = await import(path)
    return { library: await localData.getLibrary(id), templates: await localData.listTemplates(id), pipelines: await localData.listPipelines(id) }
  }, id)
}

