for (const viewport of [{ width: 320, height: 520 }, { width: 720, height: 450 }]) {
  test(`wheel scrolls over the entire modal with fixed controls at ${viewport.width}x${viewport.height}`, async ({ page }, testInfo) => {
    await page.setViewportSize(viewport)
    await createWorkspace(page, 'Scrolling team')
    const modal = page.getByRole('dialog', { name: 'Your pipeline plan starts here', exact: true })
    const backgroundScroll = await page.evaluate(() => scrollY)
    const scrollTop = () => modal.evaluate(element => element.scrollTop)
    const header = modal.locator('header'), footer = modal.locator('footer')
    const initialHeader = await header.boundingBox(), initialFooter = await footer.boundingBox()
    expect(initialHeader!.y).toBeGreaterThanOrEqual(0)
    expect(initialFooter!.y + initialFooter!.height).toBeLessThanOrEqual(viewport.height)
    for (const target of [modal.locator('.dialog-content'), header, footer]) {
      await modal.evaluate(element => { element.scrollTop = 0 })
      const box = await target.boundingBox()
      await page.mouse.move(box!.x + box!.width / 2, Math.min(box!.y + 12, viewport.height / 2))
      if (target === footer) await footer.hover()
      await page.mouse.wheel(0, 180)
      await expect.poll(scrollTop).toBeGreaterThan(0)
      const before = await scrollTop()
      await page.mouse.wheel(0, -80)
      await expect.poll(scrollTop).toBeLessThan(before)
      expect((await header.boundingBox())!.y).toBeCloseTo(initialHeader!.y, 0)
      expect((await footer.boundingBox())!.y).toBeCloseTo(initialFooter!.y, 0)
      expect(await page.evaluate(() => scrollY)).toBe(backgroundScroll)
    }
    await modal.getByRole('heading', { level: 2 }).focus()
    await modal.evaluate(element => { element.scrollTop = 0 })
    await page.keyboard.press('PageDown')
    await expect.poll(scrollTop).toBeGreaterThan(0)
    await modal.evaluate(element => { element.scrollTop = element.scrollHeight })
    await expect(modal.getByRole('link', { name: 'How it works', exact: true })).toBeInViewport()
    await page.screenshot({ path: testInfo.outputPath('scrolled-welcome.png') })
    await page.keyboard.press('Escape')
    await expect(page.getByRole('button', { name: 'Getting started', exact: true })).toBeFocused()
    expect(await page.evaluate(() => getComputedStyle(document.documentElement).overflow)).not.toBe('hidden')
  })
}

