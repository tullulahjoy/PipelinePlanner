  await modal.getByRole('button', { name: 'Got it', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Getting started', exact: true })).toHaveCount(0)
  await expect(page.getByRole('link', { name: 'How it works', exact: true })).toBeVisible()
