test.describe('touch scrolling', () => {
  test.use({ hasTouch: true, isMobile: true, viewport: { width: 390, height: 640 } })
  test('a swipe scrolls the instructions while controls and background remain fixed', async ({ page }) => {
    await createWorkspace(page, 'Touch team')
    const modal = page.getByRole('dialog', { name: 'Your pipeline plan starts here', exact: true })
    const session = await page.context().newCDPSession(page)
    const backgroundScroll = await page.evaluate(() => scrollY)
    await session.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 180, y: 460 }] })
    for (let y = 440; y >= 220; y -= 20) await session.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 180, y }] })
    await session.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await expect.poll(() => modal.evaluate(element => element.scrollTop)).toBeGreaterThan(0)
    await expect(modal.getByRole('heading', { level: 2 })).toBeInViewport()
    await expect(modal.getByRole('button', { name: 'Got it', exact: true })).toBeInViewport()
    expect(await page.evaluate(() => scrollY)).toBe(backgroundScroll)
    await session.detach()
  })
})
