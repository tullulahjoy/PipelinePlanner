test('pointer reordering previews insertion without moving rows and commits only a valid drop', async ({ page }, testInfo) => {
  await editor(page)
  for (const name of ['Evaluation', 'Moderation', 'Award review']) await browsePhase(page, name)
  const original = ['Evaluation', 'Moderation', 'Award review']
  await grip(page, 0).scrollIntoViewIfNeeded()
  const handle = (await grip(page, 0).boundingBox())!
  const last = (await page.locator('.schedule-editor-table tbody tr').last().boundingBox())!
  await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2)
  await page.mouse.down()
  await page.mouse.move(handle.x + handle.width / 2, last.y + last.height - 4, { steps: 5 })
  await expect(page.locator('.schedule-reorder-ghost')).toBeVisible()
  await expect(page.locator('.schedule-reorder-ghost')).toContainText('Evaluation → position 3')
  await expect(names(page)).toHaveText(original)
  await expect(page.locator('tr.drop-after')).toHaveCount(1)
  await page.screenshot({ path: testInfo.outputPath('drag-insertion.png') })
  await page.mouse.up()
  await expect(names(page)).toHaveText(['Moderation', 'Award review', 'Evaluation'])
  await expect(grip(page, 2)).toBeFocused()
  const again = (await grip(page, 2).boundingBox())!
  await page.mouse.move(again.x + again.width / 2, again.y + again.height / 2)
  await page.mouse.down(); await page.mouse.move(2, again.y - 30, { steps: 4 }); await page.mouse.up()
  await expect(names(page)).toHaveText(['Moderation', 'Award review', 'Evaluation'])
  await expect(page.locator('.schedule-reorder-ghost')).toBeHidden()
  await expect(page.getByRole('button', { name: /^Move item \d+ (up|down)$/ })).toHaveCount(0)
})

test('keyboard reordering supports cancellation, Home/End and focus restoration without changing dates', async ({ page }) => {
  await editor(page)
  for (const name of ['Evaluation', 'Moderation', 'Award review']) await browsePhase(page, name)
  await grip(page, 1).focus(); await page.keyboard.press('Space'); await page.keyboard.press('Home')
  await expect(names(page)).toHaveText(['Evaluation', 'Moderation', 'Award review'])
  await page.keyboard.press('Escape')
  await expect(grip(page, 1)).toBeFocused()
  await expect(page.locator('.schedule-reorder-ghost')).toBeHidden()
  await page.keyboard.press('Enter'); await page.keyboard.press('End'); await page.keyboard.press('Enter')
  await expect(names(page)).toHaveText(['Evaluation', 'Award review', 'Moderation'])
  await expect(grip(page, 2)).toBeFocused()
  await page.keyboard.press('Space'); await page.keyboard.press('Home'); await page.keyboard.press('Tab')
  await expect(names(page)).toHaveText(['Evaluation', 'Award review', 'Moderation'])
  await expect(page.locator('.schedule-reorder-ghost')).toBeHidden()
  await grip(page, 1).focus(); await page.keyboard.press('Space'); await page.keyboard.press('Home')
  await page.evaluate(() => window.dispatchEvent(new Event('blur')))
  await expect(page.locator('.schedule-reorder-ghost')).toBeHidden()
  await expect(names(page)).toHaveText(['Evaluation', 'Award review', 'Moderation'])
  await addMilestone(page, 'Service begins')
  await page.getByLabel('Anchor date', { exact: true }).fill('2032-05-12')
  await page.getByRole('button', { name: 'Preview schedule', exact: true }).click()
  await page.locator('.phase-date-details summary').click()
  await expect(page.getByRole('region', { name: 'Phase and milestone dates', exact: true })).toContainText('12 May 2032')
})

