async function editor(page: Page) {
  await page.goto('/workspaces')
  const id = await page.evaluate(async () => {
    const path = '/src/data/local-data.ts'; const { localData } = await import(path)
    const workspace = await localData.createWorkspace('Prototype behaviour team')
    for (const name of ['Evaluation', 'Moderation', 'Award review']) await localData.createPhase(workspace.id, { name, weeks: 3, color: '#315ed4', checks: [] })
    localStorage.setItem(`ltpp-app:welcome-dismissed:${workspace.id}`, '1')
    return workspace.id
  })
  await page.goto(`/workspaces/${id}/pipeline?edit=1&add=1`)
  await page.getByLabel('Procurement name', { exact: true }).fill('Service transfer')
  return id
}
const names = (page: Page) => page.locator('.schedule-editor-table .phase-label')
const grip = (page: Page, index: number) => page.locator('.schedule-editor-table tbody tr').nth(index).getByRole('button', { name: /^Move / })

